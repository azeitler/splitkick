/**
 * The Web Access service worker (#72), written into the build as `dist/sw.js`
 * by the Vite plugin in vite.config.ts.
 *
 * Why: iOS ends the web process of the Home Screen app in the background, so
 * each open is a full reload. `index.html` is `no-store`, so without a worker
 * every start needs the network, and an unreachable Mac shows a Safari error
 * page. The worker keeps the app shell:
 *
 * - Navigation: network first with a 3 s timeout, then the cached shell. Only
 *   a 200, same-origin, not-redirected HTML answer is cached (never a login
 *   page of a proxy such as Cloudflare Access). The shell is cached under one
 *   fixed key, so a `?token=` in the URL is never stored.
 * - `/assets/*`: cache first. The names are content hashes, so a cached file
 *   is never stale. Files that `index.html` loads are cached at install; lazy
 *   chunks when they are first used.
 * - Never touched: `/api/*`, `/ws`, `/preview/*`, `jean-build.json`, `sw.js`,
 *   other origins (remote connections) and all non-GET requests.
 *
 * The build id is in the file, so each build is a new worker. A new worker
 * waits until the "Reload" toast asks it to take over (`skip-waiting`), or
 * until no page uses the old one. On activate it deletes the caches of other
 * builds.
 */

export const CACHE_PREFIX = 'splitkick-shell-'
export const SHELL_KEY = '/index.html'
export const NETWORK_TIMEOUT_MS = 3000

/**
 * The same-origin `/assets/*` files that index.html loads (scripts, module
 * preloads, styles), without duplicates, in order.
 *
 * @param {string} html
 * @returns {string[]}
 */
export function precacheUrlsFromIndexHtml(html) {
  const urls = []
  for (const match of html.matchAll(/\b(?:src|href)="(\/assets\/[^"?#]+)"/g)) {
    if (!urls.includes(match[1])) urls.push(match[1])
  }
  return urls
}

/**
 * The worker itself. Plain browser JavaScript; the constants are inlined.
 *
 * @param {{ buildId: string, precacheUrls: string[] }} options
 * @returns {string}
 */
export function renderServiceWorker({ buildId, precacheUrls }) {
  return `// Splitkick Web Access service worker. Generated by
// scripts/web-service-worker.mjs; do not edit dist/sw.js.
const BUILD_ID = ${JSON.stringify(buildId)}
const CACHE = ${JSON.stringify(CACHE_PREFIX)} + BUILD_ID
const SHELL_KEY = ${JSON.stringify(SHELL_KEY)}
const PRECACHE = ${JSON.stringify(precacheUrls)}
const NETWORK_TIMEOUT_MS = ${NETWORK_TIMEOUT_MS}
const BYPASS_PREFIXES = ['/api/', '/ws', '/preview/']
const BYPASS_FILES = ['/jean-build.json', '/sw.js']

function isShellResponse(response) {
  return (
    response.ok &&
    response.status === 200 &&
    response.type === 'basic' &&
    !response.redirected &&
    (response.headers.get('content-type') || '').includes('text/html')
  )
}

self.addEventListener('install', event => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE)
      const shell = await fetch('/', { cache: 'no-store' })
      if (isShellResponse(shell)) await cache.put(SHELL_KEY, shell)
      await cache.addAll(PRECACHE)
      // The first worker takes over at once; an update waits for the page.
      if (!self.registration.active) await self.skipWaiting()
    })()
  )
})

self.addEventListener('activate', event => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys()
      await Promise.all(
        names
          .filter(name => name.startsWith(${JSON.stringify(CACHE_PREFIX)}) && name !== CACHE)
          .map(name => caches.delete(name))
      )
    })()
  )
})

self.addEventListener('message', event => {
  if (event.data && event.data.type === 'skip-waiting') self.skipWaiting()
})

async function cachedShell() {
  const cache = await caches.open(CACHE)
  return (await cache.match(SHELL_KEY)) || null
}

async function networkFirstShell(request) {
  const network = fetch(request).then(async response => {
    if (isShellResponse(response)) {
      const cache = await caches.open(CACHE)
      await cache.put(SHELL_KEY, response.clone())
    }
    return response
  })
  // After a timeout nobody may await the network answer; a later failure
  // must not become an unhandled rejection.
  network.catch(() => {})
  const timeout = new Promise(resolve =>
    setTimeout(() => resolve(null), NETWORK_TIMEOUT_MS)
  )
  try {
    const first = await Promise.race([network, timeout])
    if (first) return first
    // The server is slow: start from the cached shell, and let the network
    // answer still refresh the cache.
    const shell = await cachedShell()
    return shell || (await network)
  } catch (error) {
    const shell = await cachedShell()
    if (shell) return shell
    throw error
  }
}

async function cacheFirstAsset(request) {
  const cache = await caches.open(CACHE)
  const cached = await cache.match(request)
  if (cached) return cached
  const response = await fetch(request)
  if (response.ok && response.type === 'basic') {
    await cache.put(request, response.clone())
  }
  return response
}

self.addEventListener('fetch', event => {
  const { request } = event
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (BYPASS_PREFIXES.some(prefix => url.pathname.startsWith(prefix))) return
  if (BYPASS_FILES.includes(url.pathname)) return

  if (request.mode === 'navigate') {
    event.respondWith(networkFirstShell(request))
  } else if (url.pathname.startsWith('/assets/')) {
    event.respondWith(cacheFirstAsset(request))
  }
})
`
}
